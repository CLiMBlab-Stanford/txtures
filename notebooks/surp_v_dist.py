def tokenize(text, tokenizer):
    # input_ids will contain BOS token, but spans will not
    word_spans = np.array([m.span() for m in re.finditer(r'\S+', text)])
    encoded = tokenizer(
        text,
        return_tensors="pt",
        return_offsets_mapping=True,
        add_special_tokens=True
    )
    token_spans = encoded['offset_mapping'].numpy()[0, 1:]
    input_ids = encoded['input_ids']
    return word_spans, token_spans, input_ids


def get_sbow_onehot(tokenizer, leading_space_char='Ġ'):
    n = len(tokenizer)
    sbow = np.zeros(n)
    vocab = tokenizer.get_vocab()
    for tok in vocab:
        if tok.startswith(leading_space_char) or tok == tokenizer.bos_token:
            sbow[vocab[tok]] = 1
    sbow = torch.tensor(sbow)
    return sbow


def get_token_ids_logprobs_and_states(input_ids, model):
    assert len(input_ids.shape) == 2 and input_ids.shape[0] == 1, ('input_ids'
        'must be for a single sequence, not batch.')
    outputs = model(input_ids, labels=input_ids)
    logits = outputs.logits
    states = outputs.hidden_states

    logits = logits[..., :-1, :].contiguous()
    logprobs = torch.nn.functional.log_softmax(logits, dim=-1)
    labels = input_ids[..., 1:].contiguous()

    states = {layer: states[layer][0, 1:, :] for layer in range(len(states))}
    return labels, logprobs, states


def get_surps_from_ids_and_logprobs(labels, logprobs):
    surprisals = torch.take_along_dim(
        -logprobs,
        labels.unsqueeze(dim=-1),
        dim=-1
    )
    surprisals = surprisals.view(-1)

    return surprisals


def get_sbow_probs_from_ids_and_logpros(logprobs, sbow):
    probs = torch.exp(-logprobs)
    while len(sbow.shape) < len(probs.shape):
        sbow = sbow.unsqueeze(dim=0)
    sbow_probs = (probs * sbow).sum(dim=-1)
    return sbow_probs


def aggregate_tokens(
        word_spans,
        token_spans,
        surprisals,
        states,
        sbow_probs=None
    ):
    if not isinstance(states, dict):
        states = {layer: states[layer] for layer in range(len(states))}
    if not len(word_spans):
        return surprisals, states

    word_ends = [span[1] for span in word_spans]
    token_ends = [span[1] for span in token_spans]

    wix = 0
    tix = 0

    surprisals_ = [[]]
    states_ = {layer: [[]] for layer in states}
    sbow_probs_ = [None]
    while wix < len(word_spans) and tix < len(token_spans):
        wend = word_ends[wix]
        tend = token_ends[tix]
        assert tend <= wend, (f"Got token end index {tend} after word end index"
                              f" {wend}, which shouldn't be possible. Check "
                              f" the tokenization.\nToken spans: {token_spans}"
                              f" \nWord spans: {word_spans}")
        surprisals_[-1].append(surprisals[tix].detach().numpy())
        for layer in states:
            states_[layer][-1].append(states[layer][tix].detach().numpy())
        if sbow_probs is not None and sbow_probs_[-1] is None:
            sbow_probs_[-1] = sbow_probs[tix].detach().numpy()
        tix += 1
        if tend == wend and wix < len(word_spans):
            surprisals_[-1] = np.array(surprisals_[-1])
            surprisals_.append([])
            sbow_probs_.append(None)
            for layer in states:
                states_[layer][-1] = np.array(states_[layer][-1])
                states_[layer].append([])
            wix += 1

    surprisals_ = np.array(
        [x.sum() for x in surprisals_[:-1]]
    )
    # Do WT correction if sbow_probs available
    if sbow_probs is not None:
        sbow_probs_[-1] = sbow_probs_[-2]  # set the final and prefinal prob
                                           # to be the same so that their
                                           # ratio is 1
        sbow_probs_ = np.array(sbow_probs_)
        correction = sbow_probs_[1:] / (sbow_probs_[:-1])
        probs = np.exp(-surprisals_) * correction
        surprisals_ = -np.log(probs)

    for layer in states:
        states_[layer] = np.array(
            [np.mean(x, axis=0) for x in states_[layer][:-1]]
        )

    return surprisals_, states_


def get_word_surps_and_states(text, model, tokenizer, sbow=None):
    word_spans, token_spans, input_ids = tokenize(text, tokenizer)
    labels, logprobs, states = get_token_ids_logprobs_and_states(
        input_ids, model
    )
    surprisals = get_surps_from_ids_and_logprobs(labels, logprobs)
    if sbow is not None:
        sbow_probs = get_sbow_probs_from_ids_and_logpros(logprobs[0], sbow)
    else:
        sbow_probs = None
    surprisals, states = aggregate_tokens(
        word_spans, token_spans, surprisals, states, sbow_probs=sbow_probs
    )

    return surprisals, states


def process_texts(
        texts,
        model_name,
        verbose=True,
        N=None,
        min_len=2,
        wt_decode=False
    ):
    model = AutoModelForCausalLM.from_pretrained(
        model_name, output_hidden_states=True
    )
    tokenizer = AutoTokenizer.from_pretrained(model_name, add_bos_token=True)
    if wt_decode:
        sbow = get_sbow_onehot(tokenizer)
    else:
        sbow = None
    out = []
    n = len(texts)
    if N is not None:
        n = min(n, N)
    j = 0
    for i, text in enumerate(texts):
        if verbose:
            sys.stderr.write(f"\rProcessing text {j + 1}/{n}")
            sys.stderr.flush()
        surprisals, states = get_word_surps_and_states(
            text, model, tokenizer, sbow=sbow
        )
        if len(surprisals) < min_len:
            continue
        out.append(
            Result(
                text=text,
                surprisals=surprisals,
                states=states
            )
        )
        j += 1
        if N is not None and j >= N:
            break

    return out


def cosine_distance(A, B, axis=-1):
    dot_product = np.sum(A * B, axis=axis)
    norm_A = np.linalg.norm(A, axis=axis)
    norm_B = np.linalg.norm(B, axis=axis)

    denom = norm_A * norm_B

    return 1 - np.where(denom != 0, dot_product / denom, 0)


def zscore(A, eps=1e-8, axis=-1):
    ndim = len(A.shape)
    if isinstance(axis, int):
        axis = (axis,)
    elif axis is not None:
        axis = tuple(axis)
    if axis is not None:
        axis = tuple([a if a >= 0 else ndim + a for a in axis])
    m = np.mean(A, axis=axis, keepdims=True)
    s = np.std(A, axis=axis, keepdims=True)
    return (A - m) / (s + eps)


def euclidean_distance(A, B, standardize=True, axis=-1):
    if standardize:
        assert axis is not None, 'Cannot standardize if reducing all axes'
        ndim = len(A.shape)
        if isinstance(axis, int):
            axis = (axis,)
        else:
            axis = tuple(axis)
        axis = tuple([a if a >= 0 else ndim + a for a in axis])
        axis_ = tuple([a for a in range(ndim) if not a in axis])
        A = zscore(A, axis=axis_)
        B = zscore(B, axis=axis_)
    return np.linalg.norm(A - B, axis=axis) / np.sqrt(A.shape[-1])


def manhattan_distance(A, B, standardize=True, axis=-1):
    if standardize:
        assert axis is not None, 'Cannot standardize if reducing all axes'
        ndim = len(A.shape)
        if isinstance(axis, int):
            axis = (axis,)
        else:
            axis = tuple(axis)
        axis = tuple([a if a >= 0 else ndim + a for a in axis])
        axis_ = tuple([a for a in range(ndim) if not a in axis])
        A = zscore(A, axis=axis_)
        B = zscore(B, axis=axis_)
    return np.linalg.norm(A - B, ord=1, axis=axis) / A.shape[-1]


def infinity_distance(A, B, standardize=True, axis=-1):
    if standardize:
        assert axis is not None, 'Cannot standardize if reducing all axes'
        ndim = len(A.shape)
        if isinstance(axis, int):
            axis = (axis,)
        else:
            axis = tuple(axis)
        axis = tuple([a if a >= 0 else ndim + a for a in axis])
        axis_ = tuple([a for a in range(ndim) if not a in axis])
        A = zscore(A, axis=axis_)
        B = zscore(B, axis=axis_)
    return np.linalg.norm(A - B, ord=np.inf, axis=axis)


def spearman_distance(A, B, axis=-1):
    ranked_a = stats.rankdata(A, axis=axis)
    ranked_b = stats.rankdata(B, axis=axis)

    ranked_a = ranked_a - ranked_a.mean(axis=axis, keepdims=True)
    ranked_b = ranked_b - ranked_b.mean(axis=axis, keepdims=True)

    cov = np.sum(ranked_a * ranked_b, axis=axis)
    std_a = np.sqrt(np.sum(ranked_a**2, axis=axis))
    std_b = np.sqrt(np.sum(ranked_b**2, axis=axis))

    corr = cov / (std_a * std_b)

    return 1 - corr


def fisher_z(A, eps=1e-3):
    return np.arctanh(A * (1 - eps))


def get_state_distances_inner(
        states, metric='spearman', lag=1, use_fisher=False
):
    if not isinstance(states, dict):
        states = {layer: states[layer] for layer in range(len(states))}
    distances = {}
    if metric == 'cosine':
        f = cosine_distance
    elif metric == 'euclidean':
        f = euclidean_distance
    elif metric == 'manhattan':
        f = manhattan_distance
    elif metric == 'infinity':
        f = infinity_distance
    elif metric == 'spearman':
        f = spearman_distance
    else:
        raise ValueError(f'Unknown metric {metric}')
    for layer in states:
        distances_ = f(
            states[layer][lag:],
            states[layer][:-lag]
        )
        if metric in ['cosine', 'spearman'] and use_fisher:
            distances_ = fisher_z(distances_)
        distances[layer] = distances_
    return distances


def get_state_distances(results, metric='spearman', lags=1):
    out = []
    for result in results:
        distances = None
        for lag in range(1, lags + 1):
            distances_ = get_state_distances_inner(
                result.states, metric=metric, lag=lag
            )
            if distances is None:
                distances = {layer: [distances_[layer]] for layer in distances_}
            else:
                for layer in distances:
                    distances[layer] = [
                        x[len(x) - len(distances_[layer]):]
                        for x in distances[layer]
                    ]
                    distances[layer].append(distances_[layer])
        for layer in distances:
            distances[layer] = np.stack(distances[layer], axis=0).mean(axis=0)
            n_expected = len(result.surprisals) - lags
            n_actual = len(distances[layer])
            assert n_actual == n_expected, \
                (f'For item {results.text}, expected {n_expected} distances '
                 f'but got {n_actual}.')
        out.append(distances)
    return out


def plot_surp_dist(
        surprisals,
        distances,
        title=None,
        r=None,
        xlim=None,
        ylim=None,
        bins=100,
        contours=10,
        cmap='Blues',
        dpi=300
):
    if xlim is not None and ylim is not None:
        hist_range = [xlim, ylim]
    else:
        hist_range = None
    preds = pd.DataFrame(
        {'surprisal': surprisals}
    )
    coefs = sm.OLS(distances, sm.add_constant(preds)).fit().params
    b = coefs.const
    a_s = coefs.surprisal
    H, x_vals, y_vals, _ = plt.hist2d(
        x=surprisals,
        y=distances,
        range=hist_range,
        bins=bins
    )
    H = np.where(H > 0, H, np.nan)
    x_vals = np.linspace(x_vals.min(), x_vals.max(), len(x_vals) - 1)
    y_vals = np.linspace(y_vals.min(), y_vals.max(), len(y_vals) - 1)
    plt.close('all')

    plt.figure(figsize=(0.7, 1.5), dpi=dpi)
    x = np.linspace(x_vals.min(), x_vals.max(), 100)
    y_s = a_s * x + b
    plt.plot(
        x, y_s,
        color=matplotlib.colormaps[cmap](0.9), label='surprisal'
    )
    for spine in ['top', 'right']:
        plt.gca().spines[spine].set_visible(False)
    if title:
        plt.title(title)
    X, Y = np.meshgrid(x_vals, y_vals, indexing='ij')
    plt.contourf(X, Y, H, contours, cmap=cmap)
    plt.grid(False)
    if xlim is not None:
        plt.xlim(xlim)
        plt.xticks(ticks=xlim, labels=xlim)
        for i, tick in enumerate(plt.gca().get_xticklabels()):
            if i % 2 == 0:
                tick.set_horizontalalignment("left")
            else:
                tick.set_horizontalalignment("right")
    if ylim is not None:
        plt.ylim(ylim)
        plt.yticks(ticks=ylim, labels=ylim)
        for i, tick in enumerate(plt.gca().get_yticklabels()):
            if i % 2 == 0:
                tick.set_verticalalignment("bottom")
            else:
                tick.set_verticalalignment("top")
    if r is not None:
        plt.annotate(
            'r=%.02f' % r,
             (0.9, 0.1),
            xycoords='axes fraction',
            ha='right'
        )

    return plt.gcf()


