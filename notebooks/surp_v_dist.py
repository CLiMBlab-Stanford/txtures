"""Effect sizes"""

lm_fits = {}
for dataset in data:
    lm_fits[dataset] = {}
    surprisals = data[dataset]['surprisals']
    distances = data[dataset]['distances']
    surprisal_beta = {layer: None for layer in distances}
    surprisal_lower = {layer: None for layer in distances}
    surprisal_upper = {layer: None for layer in distances}
    surprisal_pvalue = {layer: None for layer in distances}
    probability_beta = {layer: None for layer in distances}
    probability_lower = {layer: None for layer in distances}
    probability_upper = {layer: None for layer in distances}
    probability_pvalue = {layer: None for layer in distances}

    for layer in distances:
        df = pd.DataFrame(
            {'surprisal': surprisals, 'distance': distances[layer]}
        )
        df['probability'] = np.exp(-df.surprisal)
        df.surprisal = df.surprisal / df.surprisal.std()
        df.probability = df.probability / df.probability.std()
        df = sm.add_constant(df)
        model = sm.OLS(
            df['distance'], df[['const', 'probability', 'surprisal']]
        )
        res = model.fit()
        surprisal_beta[layer] = res.params.surprisal
        surprisal_lower[layer] = res.params.surprisal - 2 * res.bse.surprisal
        surprisal_upper[layer] = res.params.surprisal + 2 * res.bse.surprisal
        probability_beta[layer] = res.params.probability
        probability_lower[layer] = res.params.probability - 2 * res.bse.probability
        probability_upper[layer] = res.params.probability + 2 * res.bse.probability
        surprisal_pvalue[layer] = res.pvalues.surprisal
        probability_pvalue[layer] = res.pvalues.probability

    lm_fits[dataset]['surprisal_beta'] = surprisal_beta
    lm_fits[dataset]['surprisal_lower'] = surprisal_lower
    lm_fits[dataset]['surprisal_upper'] = surprisal_upper
    lm_fits[dataset]['surprisal_pvalue'] = surprisal_pvalue
